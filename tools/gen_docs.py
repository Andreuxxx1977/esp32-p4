def impedance_table() -> str:
    rows = []
    for r in imp.impedance_rules():
        err = (r.achieved_ohm - r.target_ohm) / r.target_ohm * 100
        gap = f"{f(r.gap_mm, 3)} / {f(r.gap_mm / MIL_MM, 1)}" if r.gap_mm else "-"
        rows.append([code(r.netclass), f"{f(r.target_ohm, 0)} {'diff' if r.kind == 'diff' else 'SE'}",
                     f"{f(r.width_mm, 3)} / {f(r.width_mm / MIL_MM, 1)}", gap, f(r.achieved_ohm, 1),
                     f"{err:+.1f} %", esc(r.nets_hint)])
    return md_table(["Net class", "Target (ohm)", "Width mm / mil", "Gap mm / mil", "Model (ohm)",
                     "Error", "Nets"], rows, "lrrrrrl")


