def _routing() -> list[str]:
    L = ["## 6. Routing rules", ""]
    links = {l["label"]: l for l in hs_links()}
    rows = []
    usb, mipi, se, eth = rule("USB_90"), rule("MIPI_100"), rule("SE_50"), rule("ETH_100")

    def zrow(name, r, tol, guide):
        if not r:
            return [name, guide, "rule missing", "**FAIL**"]
        err = abs(r.achieved_ohm - r.target_ohm) / r.target_ohm
        geo = (f"{code(r.netclass)} w {f(r.width_mm, 3)} mm" + (f" / s {f(r.gap_mm, 3)} mm" if r.gap_mm else "")
               + f" -> {f(r.achieved_ohm, 1)} ohm ({err * 100:.1f} % off)")
        return [name, guide, geo, status(err <= tol)]

    rows.append(zrow("USB 2.0 HS / FS", usb, USB_Z_TOL, f"90 ohm differential +/-{USB_Z_TOL:.0%}"))
    rows.append(zrow("MIPI D-PHY (DSI, CSI)", mipi, MIPI_Z_TOL, f"100 ohm differential +/-{MIPI_Z_TOL:.0%}"))
