def _endpoint_counts(nets: list[str]) -> Counter:
    cnt: Counter = Counter()
    for n in nets:
        for c, pad in members(n):
            if c.ref == "U1":
                continue
            if c.part.kind in ("res", "cap"):
                if is_series(c, 100.0) and other_end(c, pad) not in RAILS:
                    for c2, _ in members(other_end(c, pad)):
                        if c2.part.kind not in ("res", "cap") and c2.ref != "U1":
                            cnt[c2.ref] += 1
            else:
                cnt[c.ref] += 1
    return cnt


def _pick(cnt: Counter, need_place: bool = True) -> list[str]:
    cands = [r for r in cnt if not need_place or board_xy(COMP[r])]
    return sorted(cands, key=lambda r: (-cnt[r], COMP[r].part.kind != "conn", natural_key(r)))


def hs_links() -> list[dict]:
    out = []
    for label, pat in HS_IFACES:
        pads = sorted((p for p, n in U1.conns.items() if re.match(pat, n)), key=int)
        if not pads:
            continue
        pts = [u1_pad_xy(p) for p in pads]
        a = (sum(x for x, _ in pts) / len(pts), sum(y for _, y in pts) / len(pts))
        target = _pick(_endpoint_counts([U1.conns[p] for p in pads]))
        if not target:
            continue
        b = board_xy(COMP[target[0]])
        out.append({"label": label, "pads": pads, "a": a, "b": b, "from": "U1", "to": target[0]})
    for label, pat, start_kind in OFFSOC_LINKS:
        nets = sorted(n for n in NETS if re.match(pat, n))
        ends = sorted(_pick(_endpoint_counts(nets))[:2], key=lambda r: COMP[r].part.kind != start_kind)
        if len(ends) >= 2:
            out.append({"label": label, "pads": [], "a": board_xy(COMP[ends[0]]),
                        "b": board_xy(COMP[ends[1]]), "from": ends[0], "to": ends[1]})
    return out


def placed_parts() -> list[bs.Component]:
    return sorted((c for c in bs.COMPONENTS if isinstance(c.place, bs.Place)
                   and c.ref != "U1" and c.part.kind != "mech"), key=lambda c: natural_key(c.ref))


def near_anchor(comp: bs.Component) -> tuple[tuple[float, float], float, str] | None:
    """(anchor xy, accumulated slack mm, description) for a Near placement."""
    slack, pl, chain = 0.0, comp.place, []
    while isinstance(pl, bs.Near):
        slack += pl.max_mm
        anchor = COMP[pl.ref]
        chain.append(f"{pl.ref}" + (f".{pl.pad}" if pl.pad else ""))
        if anchor.ref == "U1" and pl.pad:
            return u1_pad_xy(pl.pad), slack, " -> ".join(chain)
        pl = anchor.place
    if isinstance(pl, bs.Place):
        return (pl.x, pl.y), slack, " -> ".join(chain)
    return None


