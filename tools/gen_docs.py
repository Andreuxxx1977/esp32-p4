def _conflicts() -> list[str]:
    L = ["## 3. Conflict analysis", ""]
    sets = interface_sets()
    all_gpio_pads = set(p4.GPIO_PAD.values())
    rows = []
    for label, kind, g, pads in sets:
        rows.append([esc(label), kind, ranges(g) if g else "-", ranges(pads),
                     "yes" if pads <= all_gpio_pads else ("no" if not pads & all_gpio_pads else "**mixed**")])
    L += ["### 3.1 Resource sets", "",
          md_table(["Interface", "Kind", "GPIOs", "U1 pads", "Pads are GPIO pads?"], rows), ""]
    # matrix
    hdr = ["", *[esc(s[0]) for s in sets]]
    rows, lines, total = [], [], 0
    for i, (la, _, _, pa) in enumerate(sets):
        r = [f"**{esc(la)}**"]
        for j, (lb, _, _, pb) in enumerate(sets):
            if i == j:
                r.append(f"({len(pa)})")
                continue
            inter = pa & pb
            total += len(inter) if j > i else 0
            r.append("0" if not inter else f"**{ranges(inter)}**")
            if j > i:
                lines.append(f"{la:<16} & {lb:<16} = {sorted(inter, key=int) if inter else 'set()'}")
        rows.append(r)
    ded_vs_gpio = set().union(*(s[3] for s in sets if s[1] == "dedicated")) & all_gpio_pads
    L += ["### 3.2 Pairwise overlap (U1 pad numbers; diagonal = set size)", "",
          md_table(hdr, rows, "l" + "c" * len(sets)), "",
          "Intersections computed by `tools/gen_docs.py` at generation time:", "", "```text", *lines,
          f"dedicated MIPI/USB-HS pads & GPIO pads = {sorted(ded_vs_gpio, key=int) if ded_vs_gpio else 'set()'}",
          f"GPIO_MAP duplicates                    = "
          f"{sorted(g for g, n in Counter(u.gpio for u in bs.GPIO_MAP).items() if n > 1) or 'set()'}",
          "```", "",
          f"Result: **{total} overlapping pads** across {len(sets) * (len(sets) - 1) // 2} interface pairs. "
          "MIPI DSI/CSI and USB 2.0 HS live on dedicated D-PHY / UTMI pads that are not GPIOs, so they "
          "cannot collide with any GPIO-matrix or IO_MUX assignment.", ""]

    # IO_MUX legality
    rows = []
    for u in sorted(bs.GPIO_MAP, key=lambda u: u.gpio):
        if u.mux != "IO_MUX":
            continue
        sig = iomux_signal(u)
        opts = p4.IOMUX_OPTIONS.get(sig, ()) if sig else ()
        rows.append([sig or "-", code(u.net), f"GPIO{u.gpio}", "/".join(map(str, opts)) or "-",
                     status(u.gpio in opts) if sig else "not in `IOMUX_OPTIONS`"])
    L += ["### 3.3 IO_MUX-fixed signals: chosen pad vs legal pads", "",
          md_table(["Signal", "Net", "Chosen", "Legal (IOMUX_OPTIONS)", "Status"], rows), ""]

    # avoided alternatives
    chosen = {iomux_signal(u): u.gpio for u in bs.GPIO_MAP if iomux_signal(u)}
    fixed_on = defaultdict(list)
    for s, o in p4.IOMUX_OPTIONS.items():
        if len(o) == 1:
            fixed_on[o[0]].append(s)
    rows = []
    for sig, opts in p4.IOMUX_OPTIONS.items():
        if len(opts) < 2:
            continue
        ch = chosen.get(sig)
        for g in opts:
            if g == ch:
                continue
            u = USE.get(g)
            occ = f"{code(u.net)} ({esc(u.block)})" if u else ("NC" if g in bs.GPIO_NC else "-")
            reasons = []
            if u and u.block not in ("Header",) and "Ethernet" not in u.block:
                reasons.append(f"collides with {esc(u.block)} {code(u.net)}")
            fx = [s for s in fixed_on.get(g, []) if s != sig]
            if fx:
                reasons.append("pad owns fixed " + "/".join(fx))
            if p4.gpio_domain(g) == "VDD_IO_5" and g in bs.GPIO_NC:
                reasons.append(f"{p4.gpio_domain(g)} = {code(u1_net(PAD_BY_NAME['VDD_IO_5']))} (0 V at boot)")
            if g in p4.STRAPPING_GPIOS:
                reasons.append("strapping pin")
            if u and "Ethernet" in u.block:
                reasons.append(f"taken by Ethernet {code(u.net)}")
            if not reasons:
                reasons.append("free alternative, not needed" + (" (header pin)" if u and u.block == "Header" else ""))
            rows.append([sig, f"GPIO{ch}" if ch is not None else "not used", f"GPIO{g}", occ,
                         ", ".join(fx) or "-", "; ".join(reasons)])
    L += ["### 3.4 Alternative IO_MUX pads deliberately avoided", "",
          "Every multi-option IO_MUX signal in `IOMUX_OPTIONS`; each row is a legal pad the design did "
          "*not* use and what already occupies it.", "",
          md_table(["Signal", "Chosen", "Alternative", "Occupant in this design", "Fixed IO_MUX on that pad",
                    "Why avoided"], rows), ""]
    # forced choices
    sd_pads = {g for s, o in p4.IOMUX_OPTIONS.items() if s.startswith("SD0_") for g in o}
    forced = []
    for sig in (s for s in p4.IOMUX_OPTIONS if s.startswith("RMII_") and s in chosen):
        clean = [g for g in p4.IOMUX_OPTIONS[sig] if g not in sd_pads and g not in bs.GPIO_NC]
        strap = [g for g in clean if g in p4.STRAPPING_GPIOS]
        forced.append([sig, "/".join(map(str, p4.IOMUX_OPTIONS[sig])), "/".join(map(str, clean)) or "none",
                       f"GPIO{chosen.get(sig)}" if sig in chosen else "-",
                       "only non-SDIO option is a strapping pin" if clean and clean == strap else "-"])
    L += ["Legal RMII pads that do not collide with SDMMC slot 0 (GPIO "
          f"{ranges(sd_pads)}) or the NC VDD_IO_5 pads:", "",
          md_table(["Signal", "All legal", "SDIO-free", "Chosen", "Consequence"], forced), "",
          "TXD0/TXD1 have no SDIO-free option except the strapping pins GPIO34/GPIO35, which is why "
          "GPIO35 carries both RMII_TXD1 and the BOOT strap (see section 4).", ""]
    return L


def _strapping() -> list[str]:
    L = ["## 4. Strapping and boot", ""]
    rows = []
    for g in sorted(p4.STRAPPING_GPIOS):
        u = USE.get(g)
        net = u.net if u else None
        ev = evidence(net) if net else []
        ics = [f"{c.ref}.{esc(pin_name(c, pad))}" for n in ([net] if net else [])
               for c, pad in members(n) if c.part.kind == "ic" and c.ref != "U1"]
        ics += [f"{c2.ref}.{esc(pin_name(c2, p2))} via {c.ref}" for c, pad in members(net or "")
                if is_series(c, 100.0) and other_end(c, pad) not in RAILS
                for c2, p2 in members(other_end(c, pad)) if c2.part.kind == "ic" and c2.ref != "U1"]
        pulls = [e for e in ev if re.search(r" to (\+3V3|VDD\S*)$", e)]
        downs = [e for e in ev if e.endswith(f"to {GND}") and not e.startswith("SW")]
        rs = p4.RESET_STATE.get(g, "-")
        if pulls:
            level = f"1 (external pull-up {pulls[0].split()[0]})"
        elif downs:
            level = f"0 ({downs[0].split()[0]})"
        elif "WPU" in rs:
            level = "1 (internal WPU)"
        else:
            level = "undefined: no board pull" + (f" (only {', '.join(ics)} on the net)" if ics else "")
        rows.append([f"GPIO{g}", code(net or "-"), esc(rs), esc(", ".join(ev + ics) or "-"), level,
                     esc(u.notes if u else "-")])
    L += [md_table(["GPIO", "Net", "Reset state", "Netlist (pulls / switches)", "Level at reset",
                    "Spec note"], rows), ""]
    b, q = p4.BOOT_MODE_GPIO, p4.DOWNLOAD_QUALIFIER_GPIO
    bnet, qnet = USE[b].net, USE[q].net
    bev, qev = evidence(bnet), evidence(qnet)
    pull_b = next((e.split()[0] for e in bev if "to +3V3" in e), "?")
    pull_q = next((e.split()[0] for e in qev if "to +3V3" in e), "?")
    lows = [e.split()[0].split(".")[0] for e in bev if e.startswith(("SW", "Q"))]
    L += [md_table([f"GPIO{b}", f"GPIO{q}", "Boot mode", "How the board gets there"], [
        ["1", "x", "SPI boot (normal)", f"{pull_b} pull-up holds GPIO{b} high"],
        ["0", "1", "Joint download boot (UART0 / USB)",
         f"{' or '.join(lows) or '?'} pulls GPIO{b} low while CHIP_PU rises; {pull_q} keeps GPIO{q} = 1"],
        ["0", "0", "not a listed boot mode", f"prevented: nothing in the netlist pulls GPIO{q} low"],
    ], "ccll"), ""]
    pad = p4.GPIO_PAD[b]
    stubs = []
    for c, _ in members(bnet):
        if c.ref == "U1" or c.part.kind in ("res", "cap"):
            continue
        pos = board_xy(c)
        if pos is None:
            an = near_anchor(c)
            if an:
                stubs.append(f"{c.ref} ~{f(dist(u1_pad_xy(pad), an[0]), 0)} mm (near {an[2]}, +/-{f(an[1], 0)} mm)")
        else:
            stubs.append(f"{c.ref} {f(dist(u1_pad_xy(pad), pos), 0)} mm")
    L += [f"Review flag (computed): GPIO{b} is also {code(bnet)} (50 MHz RMII TX). Straight-line distance "
          f"from U1 pad {pad} to each active device on that net: {esc('; '.join(stubs))}. The BOOT button and "
          "auto-program transistor therefore add a long stub on the SoC side of the series resistor; keep "
          "the stub short or isolate it with a series resistor (~1k) at the tap -- with the "
          f"{pull_b} 10k pull-up a 1k series still gives a valid low (~0.3 V).", ""]
    undefined = [r[0] for r in rows if r[4].startswith("undefined")]
    if undefined:
        L += [f"Strapping pins with no defined level at reset: {', '.join(undefined)}. Acceptable only "
              "where the spec note says the strap value is ignored ('any value' / eFuse-gated); otherwise "
              "add a pull.", ""]
    return L


