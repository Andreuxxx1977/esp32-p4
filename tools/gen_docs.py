def thermal_model() -> dict:
    tv = bs.THERMAL_VIA
    d, t, L = tv["drill_mm"], PLATING_UM / 1000.0, imp.BOARD_THICKNESS_MM
    n = tv["grid"] ** 2
    a_ring = math.pi / 4 * (d ** 2 - (d - 2 * t) ** 2)                     # mm^2
    r_via = (L * 1e-3) / (K_CU * a_ring * 1e-6)
    r_arr = r_via / n
    a_full = math.pi / 4 * d ** 2
    r_arr_cu = (L * 1e-3) / (K_CU * a_full * 1e-6) / n
    l12 = 0.0
    for layer in imp.STACKUP:
        if layer.name == "In1.Cu":
            break
        l12 += layer.thickness_mm
    r_l12 = r_arr * l12 / L
    body = p4.BODY_MM[0] * p4.BODY_MM[1]
    tim_mm = float(re.search(r"([\d.]+)\s*mm", bs.HEATSINK["tim"]).group(1))
    r_tim = (tim_mm * 1e-3) / (K_TIM * body * 1e-6)
    epad = p4.EPAD_SIZE_MM ** 2
    r_solder = (SOLDER_UM * 1e-6) / (K_SOLDER * epad * PASTE_COVERAGE * 1e-6)
    bx, by = bs.HEATSINK["base_mm"]
    fin_h = bs.HEATSINK["height_mm"] - BASE_T_MM
    a_hs = bx * by + PIN_GRID ** 2 * 4 * PIN_SIDE_MM * fin_h                  # mm^2
    th_nat = 1 / (H_NAT * FIN_EFF_NAT * a_hs * 1e-6)
    th_fan = 1 / (H_FAN * FIN_EFF_FAN * a_hs * 1e-6)
    x0, y0, x1, y1 = bs.BOARD_OUTLINE
    a_board = 2 * (x1 - x0) * (y1 - y0) * 1e-6
    r_bd_nat = 1 / (H_NAT * a_board * BOARD_SPREAD_EFF)
    r_bd_fan = 1 / ((H_NAT + H_BOARD_EXHAUST) / 2 * a_board * BOARD_SPREAD_EFF)
    r_bot_common = THETA_JC_BOT + r_solder + r_arr
    r_gap = (GAP_PAD_MM * 1e-3) / (K_GAP_PAD * WINDOW_MM ** 2 * 1e-6)
    r_top_bare = THETA_JC_TOP + 1 / (H_NAT * body * 1e-6)
    scen = []
    for name, r_top, r_bot in (
            ("Heatsink + fan (normal)", THETA_JC_TOP + r_tim + th_fan, r_bot_common + r_bd_fan),
            ("Heatsink, fan stopped / zero-RPM", THETA_JC_TOP + r_tim + th_nat, r_bot_common + r_bd_nat),
            ("No heatsink, natural convection", r_top_bare, r_bot_common + r_bd_nat)):
        r_ja = 1 / (1 / r_top + 1 / r_bot)
        scen.append({"name": name, "r_top": r_top, "r_bot": r_bot, "r_ja": r_ja,
                     "share_bot": r_top / (r_top + r_bot)})
    p_lo = sum(x[1] for x in POWER_ESTIMATE)
    p_hi = sum(x[2] for x in POWER_ESTIMATE)
    return {"d": d, "t": t, "L": L, "n": n, "a_ring": a_ring, "r_via": r_via, "r_arr": r_arr,
            "r_arr_cu": r_arr_cu, "l12": l12, "r_l12": r_l12, "tim_mm": tim_mm, "r_tim": r_tim,
            "r_solder": r_solder, "a_hs": a_hs, "th_nat": th_nat, "th_fan": th_fan, "fin_h": fin_h,
            "a_board": a_board, "r_bd_nat": r_bd_nat, "r_bd_fan": r_bd_fan, "r_gap": r_gap,
            "scen": scen, "p_lo": p_lo, "p_hi": p_hi, "body": body}


def _power_ceiling() -> tuple[float | None, str]:
    tree = power_tree()
    row = next((r for r in tree if r["feeds"] and r["feeds"][0][1]["kind"] == "buck"
                and any(u1_net(p) == r["net"] for p in U1.conns if p4.PAD_NAME[p].startswith("VDD_HP"))), None)
    if not row:
        return None, ""
    ic = row["feeds"][0][1]["ic"]
    m = re.search(r"(\d+(?:\.\d+)?)\s*A\b", ic.part.description)
    v, _ = buck_vout(ic, row["net"])
    if not m or not v:
        return None, ""
    i = float(m.group(1))
    p = i * v + sum(x[2] for x in POWER_ESTIMATE[1:])
    return p, (f"{ic.ref} {ic.value} rated {f(i, 1)} A x {f(v, 2)} V = {f(i * v, 2)} W on VDD_HP "
               f"+ {f(sum(x[2] for x in POWER_ESTIMATE[1:]), 2)} W 3.3 V-side high estimate")


def _tile_alignment() -> tuple[int, int]:
    tv = bs.THERMAL_VIA
    g, pitch, pad = tv["grid"], tv["pitch_mm"], tv["pad_mm"]
    pos = [(i - (g - 1) / 2) * pitch for i in range(g)]
    nt = round((p4.EPAD_SIZE_MM - p4.EPAD_TILE_MM) / p4.EPAD_TILE_PITCH_MM) + 1
    tiles = [(j - (nt - 1) / 2) * p4.EPAD_TILE_PITCH_MM for j in range(nt)]
    inside = sum(1 for p in pos if any(abs(p - c) + pad / 2 <= p4.EPAD_TILE_MM / 2 + 1e-9 for c in tiles))
    return inside ** 2, g * g


