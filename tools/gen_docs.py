def power_tree() -> list[dict]:
    """Breadth-first walk from the USB VBUS pins through series power elements.

    Each row: {"net", "feeds": [(parent_net, via_dict)]}; source rows have no feeds.
    """
    sources = []
    for c in sorted(bs.COMPONENTS, key=lambda c: natural_key(c.ref)):
        if c.part.kind == "conn":
            for pad, nm in c.part.pins:
                if nm == "VBUS" and pad in c.conns and c.conns[pad] not in sources:
                    sources.append(c.conns[pad])
    rows = {s: {"net": s, "feeds": []} for s in sources}
    order, queue = list(sources), list(sources)
    while queue:
        net = queue.pop(0)
        edges = []
        for c, pad in members(net):
            nm = pin_name(c, pad)
            if c.dnp:
                continue
            if c.ref == "U1":
                if nm == "VDD_LDO":
                    for p2, n2 in sorted(U1.conns.items(), key=lambda kv: int(kv[0])):
                        if p4.PAD_TYPE.get(p2) == "power_out":
                            edges.append((n2, {"kind": "ldo", "refs": ["U1"],
                                               "label": f"U1 on-chip LDO {p4.PAD_NAME[p2]} (pad {p2})"}))
                continue
            if c.part.kind == "diode" and {n for _, n in c.part.pins} == {"A", "K"} and nm == "A":
                edges.append((net_of(c, "K"), {"kind": "diode", "refs": [c.ref],
                                               "label": f"{c.ref} {c.value}"}))
            elif c.part.kind == "fb" and two_pin(c):
                edges.append((other_end(c, pad), {"kind": "fb", "refs": [c.ref],
                                                  "label": f"{c.ref} {c.value}"}))
            elif c.part.kind == "res" and two_pin(c) and ohms(c.value) == 0:
                edges.append((other_end(c, pad), {"kind": "0R", "refs": [c.ref], "label": f"{c.ref} 0R"}))
            elif c.part.kind == "fet" and nm == "S" and net_of(c, "D"):
                edges.append((net_of(c, "D"), {"kind": "switch", "refs": [c.ref],
                                               "label": f"{c.ref} {c.value} load switch"}))
            elif c.part.kind == "ic" and re.match(r"^P?VIN$", nm):
                sw = net_of(c, "SW")
                ind = [d for d, _ in members(sw or "") if d.part.kind == "ind"]
                if sw and ind:
                    pad_sw = next(p for p, n in ind[0].conns.items() if n == sw)
                    edges.append((other_end(ind[0], pad_sw),
                                  {"kind": "buck", "refs": [c.ref, ind[0].ref], "ic": c,
                                   "label": f"{c.ref} {c.value} buck + {ind[0].ref} {ind[0].value}"}))
        for child, via in edges:
            if not child or child == GND or child in sources:
                continue
            if child in rows and via["kind"] != "diode":
                continue            # undirected element pointing back up the tree
            if child not in rows:
                rows[child] = {"net": child, "feeds": []}
                order.append(child)
                queue.append(child)
            if all(v["label"] != via["label"] for _, v in rows[child]["feeds"]):
                rows[child]["feeds"].append((net, via))
    return [rows[n] for n in order]


def buck_vout(ic: bs.Component, out_net: str) -> tuple[float | None, str]:
    vfb = BUCK_VFB.get(ic.value)
    fb = net_of(ic, "FB")
    top = resistors_between(out_net, fb) if fb else []
    bot = resistors_between(fb, GND) if fb else []
    if vfb is None or not top or not bot:
        return None, ""
    rt, rb = ohms(top[0].value), ohms(bot[0].value)
    v = vfb * (1 + rt / rb)
    return v, f"{f(vfb, 1)} V x (1 + {top[0].ref} {top[0].value} / {bot[0].ref} {bot[0].value})"


def rail_voltage(tree: list[dict]) -> dict[str, tuple[str, str]]:
    """net -> (short voltage, how it is set)."""
    volt: dict[str, tuple[str, str]] = {}
    for row in tree:
        net = row["net"]
        if not row["feeds"]:
            volt[net] = ("5 V", "USB VBUS")
            continue
        parent, via = row["feeds"][0]
        if via["kind"] == "buck":
            v, how = buck_vout(via["ic"], net)
            volt[net] = (f"{f(v, 2)} V", how) if v else ("see regulator", "")
        elif via["kind"] == "diode":
            refs = ", ".join(v["refs"][0] for _, v in row["feeds"])
            volt[net] = (f"VBUS - V_F", f"Schottky OR ({refs})")
        elif via["kind"] == "ldo":
            volt[net] = ("SoC LDO", "set by firmware / eFuse")
        else:
            volt[net] = (volt.get(parent, ("-", ""))[0], f"= {parent}")
    return volt


def rail_loads(net: str, exclude: set[str]) -> str:
    refs, u1pads = [], []
    for c, pad in members(net):
        if c.ref == "U1":
            u1pads.append(pad)
        elif c.part.kind not in ("res", "cap", "fb", "ind") and c.ref not in exclude and c.ref not in refs:
            refs.append(c.ref)
    parts = []
    if u1pads:
        parts.append(f"U1 pads {ranges(u1pads)}")
    parts += [f"{r} {COMP[r].value}" for r in refs]
    return ", ".join(parts) or "-"


def interface_sets() -> list[tuple[str, str, set[int], set[str]]]:
    """(label, kind, gpios, pads) for the conflict analysis."""
    def gp(pred):
        g = {u.gpio for u in bs.GPIO_MAP if pred(u)}
        return g, {p4.GPIO_PAD[x] for x in g}

    def ded(pred):
        return {pad for name, spec in p4.DEDICATED_PADS.items() if pred(name) for pad in pad_range(spec)}

    sets = []
    for label, pred in (("RMII / Ethernet", lambda u: "Ethernet" in u.block),
                        ("SDIO (microSD)", lambda u: u.block == "microSD"),
                        ("USB Serial/JTAG", lambda u: u.block == "USB-JTAG"),
                        ("UART0", lambda u: u.block == "Debug UART")):
        g, pads = gp(pred)
        sets.append((label, "GPIO", g, pads))
    for label, pred in (("MIPI DSI + CSI", lambda n: "MIPI" in n),
                        ("USB 2.0 HS", lambda n: "USB 2.0 HS" in n)):
        sets.append((label, "dedicated", set(), ded(pred)))
    for label, _, g, pads in sets:
        if not pads:
            raise SystemExit(f"gen_docs: interface set '{label}' is empty -- spec block names changed?")
    return sets


