# ===========================================================================
# Formatting helpers
# ===========================================================================

def natural_key(s: str) -> list:
    return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", s)]


def f(x: float, nd: int = 2) -> str:
    v = round(float(x), nd)
    if v == 0:
        v = 0.0
    return f"{v:.{nd}f}"


def xy(p: tuple[float, float], nd: int = 1) -> str:
    return f"({f(p[0], nd)}, {f(p[1], nd)})"


def esc(s: object) -> str:
    """Escape a plain-text table cell (GFM: '|' splits cells, '~' strikes through)."""
    return str(s).replace("|", "\\|").replace("~", "\\~").replace("\n", " ")


def code(s: object) -> str:
    return "`" + str(s).replace("|", "\\|") + "`"


def md_table(headers: list[str], rows: list[list[str]], align: str | None = None) -> str:
    align = align or "l" * len(headers)
    sep = {"l": "---", "r": "---:", "c": ":---:"}
    out = ["| " + " | ".join(headers) + " |",
           "| " + " | ".join(sep[a] for a in align) + " |"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def refs_join(refs) -> str:
    return ", ".join(sorted(refs, key=natural_key))


def ref_ranges(refs) -> str:
    """['R12','R13','R14','R20'] -> 'R12-R14, R20'."""
    by_pfx: dict[str, list[int]] = defaultdict(list)
    other = []
    for r in refs:
        m = re.fullmatch(r"([A-Z_]+?)(\d+)", r)
        if m:
            by_pfx[m.group(1)].append(int(m.group(2)))
        else:
            other.append(r)
    out = []
    for pfx in sorted(by_pfx):
        for chunk in ranges(by_pfx[pfx]).split(", "):
            a, _, b = chunk.partition("-")
            out.append(f"{pfx}{a}" + (f"-{pfx}{b}" if b else ""))
    return ", ".join(out + sorted(other, key=natural_key)) or "-"


def ranges(nums) -> str:
    """[1,2,3,5] -> '1-3, 5'."""
    nums = sorted(set(int(n) for n in nums))
    out, i = [], 0
    while i < len(nums):
        j = i
        while j + 1 < len(nums) and nums[j + 1] == nums[j] + 1:
            j += 1
        out.append(str(nums[i]) if i == j else f"{nums[i]}-{nums[j]}")
        i = j + 1
    return ", ".join(out)


def status(ok: bool, warn: bool = False) -> str:
    return "OK" if ok else ("CHECK" if warn else "**FAIL**")


