def _bom_note(line: dict) -> str:
    part = line["part"]
    notes = []
    if line["dnp"]:
        notes.append("DO NOT POPULATE")
        comp_notes = sorted({COMP[r].note for r in line["refs"] if COMP[r].note})
        notes += comp_notes
    else:
        if part.tht:
            notes.append("THT, top side")
        elif re.search(r"\bTHT\b", part.description):
            notes.append("SMD with THT legs (paste-in-hole / hand-solder the legs)")
        if part is U1.part:
            notes.append("EPAD on the capped via-in-pad array")
        m = re.search(r"([\d.]+) mm pitch", part.package)
        if m and float(m.group(1)) <= 0.4:
            notes.append(f"fine pitch {m.group(1)} mm")
        if re.search(r"PENDING|UNVERIFIED", part.pin_source + part.description, re.I):
            notes.append("PENDING verification: " + part.pin_source)
        if not part.lcsc:
            notes.append("no LCSC number")
    return "; ".join(notes)


def bom_rows() -> list[tuple[bool, list[str]]]:
    lines = bs.bom_lines()
    ordered = [l for l in lines if not l["dnp"]] + [l for l in lines if l["dnp"]]
    rows = []
    for item, line in enumerate(ordered, 1):
        part = line["part"]
        refs = sorted(line["refs"], key=natural_key)
        fp = part.footprint.split(":")[-1]
        rows.append((bool(line["dnp"]), [
            str(item), ", ".join(refs), str(line["qty"]), str(line["value"]), f"{part.package} [{fp}]",
            part.mpn, part.manufacturer, part.description, "THT" if part.tht else "SMD", part.lcsc,
            _bom_note(line)]))
    return rows


