def pin_name(comp: bs.Component, pad: str) -> str:
    return dict(comp.part.pins).get(pad, pad)


def net_of(comp: bs.Component, name: str) -> str | None:
    for pad, nm in comp.part.pins:
        if nm == name and pad in comp.conns:
            return comp.conns[pad]
    return None


def other_end(comp: bs.Component, pad: str) -> str | None:
    others = [n for p, n in comp.conns.items() if p != pad]
    return others[0] if len(set(others)) == 1 else None


def ohms(value: str) -> float | None:
    m = re.fullmatch(r"([0-9]*\.?[0-9]+)\s*([kKM]?)(?:R|ohm)?", value.strip())
    if not m:
        return None
    return float(m.group(1)) * {"": 1.0, "k": 1e3, "K": 1e3, "M": 1e6}[m.group(2)]


def members(net: str) -> list[tuple[bs.Component, str]]:
    return sorted(((COMP[r], p) for r, p in NETS.get(net, [])),
                  key=lambda cp: (natural_key(cp[0].ref), natural_key(cp[1])))


def two_pin(comp: bs.Component) -> bool:
    return len(set(comp.conns.values())) == 2 and len(comp.part.pad_numbers) <= 2


def _rails() -> set[str]:
    rails = {GND} | {n for n in NETS if bs.netclass_of(n) == "POWER"}
    for c in bs.COMPONENTS:
        if c.part.kind != "ic":
            continue
        for pad, net in c.conns.items():
            if re.match(r"^(VDD|VCC|VIO|AVIN|PVIN|VIN|VREGIN)", pin_name(c, pad)):
                rails.add(net)
    return rails


RAILS = _rails()


def resistors_between(a: str, b: str) -> list[bs.Component]:
    return sorted((c for c in bs.COMPONENTS if c.part.kind == "res" and set(c.conns.values()) == {a, b}),
                  key=lambda c: natural_key(c.ref))


def is_series(comp: bs.Component, limit: float = 1000.0) -> bool:
    v = ohms(comp.value)
    return comp.part.kind == "res" and two_pin(comp) and v is not None and v <= limit


def evidence(net: str) -> list[str]:
    """Pull resistors, switches and transistors on ``net`` (following one series resistor)."""
    out: list[str] = []

    def scan(n: str, via: str | None, skip: set[str]) -> None:
        for c, pad in members(n):
            if c.ref in skip or c.ref == "U1":
                continue
            dnp = " (DNP)" if c.dnp else ""
            tail = f" via {via}" if via else ""
            if c.part.kind == "res" and two_pin(c):
                other = other_end(c, pad)
                if other in RAILS:
                    out.append(f"{c.ref} {c.value}{dnp} to {other}{tail}")
                elif via is None and is_series(c):
                    scan(other, f"{c.ref} {c.value}", skip | {c.ref})
            elif c.part.kind == "sw":
                out.append(f"{c.ref} to {other_end(c, pad)}{tail}")
            elif c.part.kind == "fet":
                out.append(f"{c.ref}.{pin_name(c, pad)}{tail}")

    scan(net, None, set())
    return out


def describe(net: str, exclude: frozenset[str] = frozenset({"U1"}), depth: int = 0) -> list[str]:
    """Human-readable list of what hangs on ``net`` (one series-resistor hop is followed)."""
    items = []
    for c, pad in members(net):
        if c.ref in exclude:
            continue
        dnp = " (DNP)" if c.dnp else ""
        if c.part.kind in ("res", "cap", "fb") and two_pin(c):
            other = other_end(c, pad)
            if depth == 0 and c.part.kind == "res" and other not in RAILS and is_series(c):
                far = describe(other, exclude | {c.ref}, depth + 1)
                items.append(f"{c.ref} {c.value}{dnp} -> {code(other)} -> " + (", ".join(far) or "-"))
            else:
                items.append(f"{c.ref} {c.value}{dnp} to {code(other)}")
        else:
            pn = pin_name(c, pad)
            items.append(f"{c.ref}.{pad}" + (f" ({esc(pn)})" if pn != pad else ""))
    return items


def reach(nets, limit: float = 100.0) -> list[str]:
    """Non-passive parts on ``nets`` or one low-ohm series resistor away (U1 included)."""
    found: list[str] = []
    for n in nets:
        for c, pad in members(n):
            if c.part.kind in ("res", "cap"):
                far = other_end(c, pad) if is_series(c, limit) else None
                if far and far not in RAILS:
                    found += [c2.ref for c2, _ in members(far) if c2.part.kind not in ("res", "cap")]
            else:
                found.append(c.ref)
    return sorted(set(found), key=natural_key)


def soc_crystal() -> bs.Component | None:
    xt = [c for c in bs.COMPONENTS if c.part.kind == "xtal"]
    return next((c for c in xt if "U1" in reach(set(c.conns.values()) - {GND})), None)


def board_xy(comp: bs.Component) -> tuple[float, float] | None:
    return (comp.place.x, comp.place.y) if isinstance(comp.place, bs.Place) else None


def u1_pad_xy(pad: str) -> tuple[float, float]:
    """Pad centre in board coordinates (applies U1 placement + KiCad rotation)."""
    px, py = p4.pad_position(pad)
    pl = U1.place
    th = math.radians(pl.rot)
    return (pl.x + px * math.cos(th) + py * math.sin(th),
            pl.y - px * math.sin(th) + py * math.cos(th))


def dist(a, b) -> float:
    return math.hypot(a[0] - b[0], a[1] - b[1])


def seg_dist(p, a, b) -> float:
    ax, ay = a
    dx, dy = b[0] - ax, b[1] - ay
    L2 = dx * dx + dy * dy
    t = 0.0 if L2 == 0 else max(0.0, min(1.0, ((p[0] - ax) * dx + (p[1] - ay) * dy) / L2))
    return math.hypot(p[0] - (ax + t * dx), p[1] - (ay + t * dy))


def keepout_clearance(p) -> float:
    """Distance from a point to the heatsink keep-out square (negative = inside)."""
    dx, dy = abs(p[0]) - KO, abs(p[1]) - KO
    if dx <= 0 and dy <= 0:
        return max(dx, dy)
    return math.hypot(max(dx, 0.0), max(dy, 0.0))


def direction(p) -> str:
    ang = math.degrees(math.atan2(-p[1], p[0])) % 360     # +Y is down in KiCad
    names = ("right", "top-right", "top", "top-left", "left", "bottom-left", "bottom", "bottom-right")
    return names[int(((ang + 22.5) % 360) // 45)]


def iomux_signal(use: bs.GpioUse) -> str | None:
    hits = []
    for sig in p4.IOMUX_OPTIONS:
        aliases = {sig, sig.replace("SD0_", "SD_")}
        if use.net in aliases or re.search(rf"(?<![A-Z0-9_]){re.escape(sig)}(?![A-Z0-9_])", use.function):
            hits.append(sig)
    return hits[0] if len(hits) == 1 else None


def pad_range(spec: str) -> list[str]:
    a, _, b = spec.partition("-")
    return [str(n) for n in range(int(a), int(b or a) + 1)]


DEDICATED_GROUP = {pad: name for name, spec in p4.DEDICATED_PADS.items() for pad in pad_range(spec)}


def u1_net(pad: str) -> str | None:
    return U1.conns.get(pad)


def gpio_of_net(net: str | None) -> int | None:
    u = USE_BY_NET.get(net or "")
    return u.gpio if u else None


def verification_flags() -> list[tuple[str, str, str]]:
    """(where, item, text) for every spec string that says PENDING / verify / tune."""
    pat = re.compile(r"PENDING|UNVERIFIED|verify|to be matched|tune on first|cross-check", re.I)
    out = []
    for part in sorted(bs.PARTS.values(), key=lambda p: natural_key(p.key)):
        for field in ("pin_source", "description"):
            txt = getattr(part, field)
            if pat.search(txt):
                out.append((f"part {part.key}", field, txt))
    seen = set()
    for c in sorted(bs.COMPONENTS, key=lambda c: natural_key(c.ref)):
        if c.note and pat.search(c.note) and c.note not in seen:
            seen.add(c.note)
            refs = [d.ref for d in bs.COMPONENTS if d.note == c.note]
            out.append((refs_join(refs), "note", c.note))
    return out


