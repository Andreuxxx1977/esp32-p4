#!/usr/bin/env python3
"""Pure-Python KiCad 9 project writer for the ESP32-P4 "Extreme Performance" board.

No pcbnew needed. Turns the layout plan (``layout_plan.py``) into a project
anyone can download and open::

    hardware/output/esp32p4_extreme.kicad_pcb   board, KiCad 9 file format (version 20241229)
    hardware/output/esp32p4_extreme.kicad_pro   project: net classes, patterns, HDI rules, severities
    hardware/output/esp32p4_extreme.kicad_dru   custom DRC rules (generated by layout_plan)

The board is PLACED but UNROUTED: every pad carries its net (ratsnest only),
zones are drawn but not filled (press B in KiCad), no tracks exist yet.

Footprints are the real KiCad library footprints: the ``.kicad_mod`` text of
the official KiCad 10 library (gitlab.com/kicad/libraries/kicad-footprints, tag
``layout_plan.LIBRARY_TAG`` = 10.0.6, the pad names board_spec uses), cached
under ``$KICAD_FP_CACHE`` (default ``~/.cache/esp32p4-footprints``)/10.0.6/;
missing files are downloaded unless ``--offline``. U1 is generated from
``esp32p4_pinout``.

File format: the board is written in the KiCad 9.0 format (version 20241229),
which KiCad 9 and KiCad 10 both open (KiCad 10 upgrades it on save). The only
10.0 footprint token KiCad 9 rejects, ``(duplicate_pad_numbers_are_jumpers no)``,
is dropped (it is the default).

Placing a library footprint in a board file follows what pcbnew itself writes
(checked against boards saved by KiCad 9.0.8): the footprint gets ``(at X Y o)``;
children keep footprint-relative positions; pad and text angles are absolute
(local + o on the top side); a bottom-side footprint stores its children
mirrored in local Y, with layers swapped, angles ``o - local`` and texts
``(justify mirror)``; footprint-owned zones are stored in board coordinates.

Usage::

    python3 -m hardware.pcbnew.write_kicad_pcb [-o hardware/output/esp32p4_extreme.kicad_pcb]
        [--cache DIR] [--offline] [--top-only]
"""

