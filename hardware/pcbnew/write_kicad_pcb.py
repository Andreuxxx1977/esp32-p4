def u1_mod() -> list:
    """The generated ESP32-P4 footprint as a .kicad_mod tree (footprint frame)."""
    geom = lp.u1_geometry()
    f, c = lp.U1_FAB_HALF_MM, lp.U1_COURTYARD_HALF_MM

    def line(layer, a, b, w):
        return ["fp_line", ["start", a[0], a[1]], ["end", b[0], b[1]],
                ["stroke", ["width", w], ["type", "solid"]], ["layer", Q(layer)]]

    def prop(name, value, at, layer, hide=False):
        node = ["property", Q(name), Q(value), ["at", at[0], at[1], 0.0], ["layer", Q(layer)]]
        if hide:
            node.append(["hide", "yes"])
        node.append(["effects", ["font", ["size", 1.0, 1.0], ["thickness", 0.15]]])
        return node

    t = ["footprint", Q("ESP32-P4"), ["layer", Q("F.Cu")],
         ["descr", Q(geom.description + "; solid 7.5 mm EPAD, paste 3x3 windows")],
         prop("Reference", "REF**", (0.0, -6.4), "F.SilkS"),
         prop("Value", "ESP32-P4", (0.0, 6.4), "F.Fab"),
         prop("Datasheet", "", (0.0, 0.0), "F.Fab", True),
         prop("Description", "", (0.0, 0.0), "F.Fab", True),
         prop("Height", f"{p4.HEIGHT_MAX_MM:.2f} mm", (0.0, 0.0), "F.Fab", True),
         ["attr", "smd"]]
    s, k = 5.15, 4.70
    for sx in (-1, 1):
        for sy in (-1, 1):
            t.append(line("F.SilkS", (sx * s, sy * s), (sx * k, sy * s), 0.12))
            t.append(line("F.SilkS", (sx * s, sy * s), (sx * s, sy * k), 0.12))
    t.append(["fp_circle", ["center", -5.45, -5.45], ["end", -5.33, -5.45],
              ["stroke", ["width", 0.12], ["type", "solid"]], ["fill", "yes"], ["layer", Q("F.SilkS")]])
    t.append(["fp_rect", ["start", -c, -c], ["end", c, c], ["stroke", ["width", 0.05], ["type", "solid"]],
              ["fill", "no"], ["layer", Q("F.CrtYd")]])
    fab = [(-f + 1.0, -f), (f, -f), (f, f), (-f, f), (-f, -f + 1.0)]
    t.append(["fp_poly", ["pts", *[["xy", x, y] for x, y in fab]],
              ["stroke", ["width", 0.1], ["type", "solid"]], ["fill", "no"], ["layer", Q("F.Fab")]])
    t.append(["fp_text", "user", Q("${REFERENCE}"), ["at", 0.0, 0.0, 0.0], ["layer", Q("F.Fab")],
              ["effects", ["font", ["size", 1.0, 1.0], ["thickness", 0.15]]]])
    for pad in geom.pads:
        if pad.number == "105":
            t.append(["pad", Q("105"), "smd", "rect", ["at", 0.0, 0.0], ["size", pad.sx, pad.sy],
                      ["layers", Q("F.Cu"), Q("F.Mask")], ["zone_connect", 2]])
        else:
            t.append(["pad", Q(pad.number), "smd", "oval", ["at", pad.x, pad.y], ["size", pad.sx, pad.sy],
                      ["layers", Q("F.Cu"), Q("F.Mask"), Q("F.Paste")]])
    tile, pitch = p4.EPAD_TILE_MM, p4.EPAD_TILE_PITCH_MM
    for i in (-1, 0, 1):
        for j in (-1, 0, 1):
            t.append(["pad", Q(""), "smd", "rect", ["at", i * pitch, j * pitch], ["size", tile, tile],
                      ["layers", Q("F.Paste")], ["solder_paste_margin", -0.2]])
    t.append(["model", Q(lp.U1_MODEL), ["offset", ["xyz", 0, 0, 0]], ["scale", ["xyz", 1, 1, 1]],
              ["rotate", ["xyz", 0, 0, 0]]])
    t.append(["embedded_fonts", "no"])
    return t


class FootprintSource:
    def __init__(self, cache: Path, offline: bool):
        self.cache, self.offline = cache, offline
        self._memo: dict[str, list] = {}

    def get(self, lib_id: str) -> list:
        if lib_id == lp.U1_LIB_ID:
            return u1_mod()
        if lib_id not in self._memo:
            path = lp._fetch(self.cache, lp.LIBRARY_TAG, lib_id, fetch=not self.offline)
            if path is None:
                raise FileNotFoundError(f"{lib_id}: not in {self.cache} (run without --offline)")
            self._memo[lib_id] = parse(path.read_text())
        return self._memo[lib_id]


def _f(v) -> float:
    return float(v)


class Placer:
    """Copies one library footprint tree into the board at a planned placement."""

    def __init__(self, pl: lp.Placement, comp, nets: dict[str, int], uu: Uuids):
        self.pl, self.comp, self.nets, self.uu = pl, comp, nets, uu
        self.o = norm180(pl.rot)
        self.bottom = pl.side == "B"
        self.bx, self.by = board_xy(pl.x, pl.y)
        self.pad_nets: dict[str, str] = {}       # footprint pad number -> net (set in build)

    # ---- helpers
    def angle(self, local: float) -> float:
        return norm360(self.o - local if self.bottom else self.o + local)

    def ly(self, y) -> float:
        return -_f(y) if self.bottom else _f(y)

    def layer(self, name: str) -> Q:
        return Q(swap_layer(name) if self.bottom else name)

    def xform_points(self, node: list) -> list:
        """Mirror footprint-relative points of graphics / primitives for the bottom side."""
        out = [node[0]]
        for c in node[1:]:
            if isinstance(c, list) and c and c[0] in ("start", "mid", "end", "center", "xy"):
                out.append([c[0], _f(c[1]), self.ly(c[2])])
            elif isinstance(c, list):
                out.append(self.generic(c))
            else:
                out.append(c)
        return out

    def generic(self, node: list) -> list:
        head = node[0]
        if head == "uuid":
            return ["uuid", self.uu(self.pl.ref)]
        if head == "layer":
            return ["layer", self.layer(node[1])]
        if head == "layers":
            return ["layers", *[self.layer(x) for x in node[1:]]]
        if head in ("fp_line", "fp_rect", "fp_arc", "fp_circle", "fp_poly", "fp_curve",
                    "gr_line", "gr_rect", "gr_arc", "gr_circle", "gr_poly", "gr_curve", "pts"):
            return self.xform_points(node)
        return [c if not isinstance(c, list) else self.generic(c) for c in node]

    def text(self, node: list) -> list:
        """property / fp_text: footprint-relative position, absolute angle, mirror on B."""
        out = []
        for c in node:
            if isinstance(c, list) and c and c[0] == "at":
                local = _f(c[3]) if len(c) > 3 and c[3] not in ("unlocked",) else 0.0
                extra = [x for x in c[3:] if x == "unlocked"]
                out.append(["at", _f(c[1]), self.ly(c[2]), self.angle(local), *extra])
            elif isinstance(c, list) and c and c[0] == "effects":
                eff = [x if not isinstance(x, list) else self.generic(x) for x in c]
                if self.bottom:
                    j = child(eff, "justify")
                    if j is None:
                        eff.append(["justify", "mirror"])
                    elif "mirror" in j:
                        j.remove("mirror")
                    else:
                        j.append("mirror")
                out.append(eff)
            elif isinstance(c, list):
                out.append(self.generic(c))
            else:
                out.append(c)
        return out

    def pad(self, node: list) -> list:
        out = []
        number = node[1]
        for c in node:
            if isinstance(c, list) and c and c[0] == "at":
                local = _f(c[3]) if len(c) > 3 else 0.0
                a = self.angle(local)
                out.append(["at", _f(c[1]), self.ly(c[2])] + ([a] if a else []))
            elif isinstance(c, list) and c and c[0] == "primitives":
                out.append(self.generic(c))
            elif isinstance(c, list) and c and c[0] == "drill":
                d = [x if not (isinstance(x, list) and x[0] == "offset")
                     else ["offset", _f(x[1]), self.ly(x[2])] for x in c]
                out.append(d)
            elif isinstance(c, list) and c and c[0] in ("net", "uuid"):
                continue                              # re-added below
            elif isinstance(c, list):
                out.append(self.generic(c))
            else:
                out.append(c)
        net = self.pad_nets.get(number)
        if net is not None:
            out.append(["net", self.nets[net], Q(net)])
        out.append(["uuid", self.uu(self.pl.ref)])
        return out

    def zone(self, node: list) -> list:
        """Footprint-owned zones are stored in board coordinates."""
        def xy(c):
            x, y = lp.to_board(_f(c[1]), _f(c[2]), self.pl.x, self.pl.y, self.pl.rot, self.pl.side)
            bx, by = board_xy(x, y)
            return ["xy", bx, by]

        def walk(n):
            if not isinstance(n, list):
                return n
            if n and n[0] == "xy":
                return xy(n)
            if n and n[0] in ("uuid", "layer", "layers"):
                return self.generic(n)
            return [walk(c) for c in n]
        return walk(node)

    # ---- the footprint
    def build(self, src: list) -> list:
        pl, comp = self.pl, self.comp
        numbers = [c[1] for c in children(src, "pad")]
        if comp:
            mapping, _ = lp.map_pads(comp, list(numbers))
            for spec_pad, net in comp.conns.items():
                for fp_pad in mapping.get(spec_pad, ()):
                    self.pad_nets[fp_pad] = net
        lib_id = pl.lib_id
        at = ["at", self.bx, self.by] + ([self.o] if self.o else [])
        fp = ["footprint", Q(lib_id), ["layer", Q("B.Cu" if self.bottom else "F.Cu")],
              ["uuid", self.uu(pl.ref)], at]
        value = comp.value if comp else ("Fiducial" if pl.ref.startswith("FID") else src[1])
        have_attr = False
        for c in src[2:]:
            if not isinstance(c, list):
                continue
            head = c[0]
            if head in ("version", "generator", "generator_version", "layer", "uuid", "at"):
                continue
            if head in NEWER_THAN_9:          # KiCad 10 library syntax, not in the 9.0 format
                if c[1:] not in (["no"], []):
                    raise ValueError(f"{pl.lib_id}: ({head} {c[1:]}) cannot be expressed in KiCad 9")
                continue
            if head == "property":
                name = c[1]
                node = self.text(c)
                if name == "Reference":
                    node[2] = Q(pl.ref)
                    if not pl.ref_on_silk:
                        lay = child(node, "layer")
                        lay[1] = Q("B.Fab" if self.bottom else "F.Fab")
                    elif pl.ref_xy:                   # planned, pad-free, upright position
                        lx, ly = lp.rotate(pl.ref_xy[0] - pl.x, pl.ref_xy[1] - pl.y, -pl.rot)
                        at = child(node, "at")
                        at[1:] = [round(lx, 6), round(ly, 6), 0.0]
                        font = child(child(node, "effects"), "font")
                        font[:] = ["font", ["size", pl.ref_size, pl.ref_size],
                                   ["thickness", round(0.15 * pl.ref_size, 4)]]
                elif name == "Value":
                    node[2] = Q(value)
                fp.append(node)
                continue
            if head == "attr":
                attr = list(c)
                if comp and comp.dnp and "dnp" not in attr:
                    attr.append("dnp")
                if pl.ref.startswith("FID") and "exclude_from_bom" not in attr:
                    attr.append("exclude_from_bom")
                fp.append(attr)
                have_attr = True
                self._extra_properties(fp)
                continue
            if head == "fp_text":
                fp.append(self.text(c))
            elif head == "pad":
                fp.append(self.pad(c))
            elif head == "zone":
                fp.append(self.zone(c))
            elif head == "model":
                fp.append(c)
            else:
                fp.append(self.generic(c))
        if not have_attr:
            self._extra_properties(fp)
        return fp

    def _extra_properties(self, fp: list) -> None:
        comp = self.comp
        if not comp:
            return
        fields = [("MPN", comp.part.mpn), ("Manufacturer", comp.part.manufacturer),
                  ("LCSC", comp.part.lcsc)]
        for name, value in fields:
            if not value:
                continue
            fp.append(["property", Q(name), Q(value), ["at", 0.0, 0.0, self.angle(0.0)],
                       ["layer", Q("B.Fab" if self.bottom else "F.Fab")], ["hide", "yes"],
                       ["uuid", self.uu(self.pl.ref)],
                       ["effects", ["font", ["size", 1.0, 1.0], ["thickness", 0.15]]]
                       + ([["justify", "mirror"]] if self.bottom else [])])


