def write(out: Path = DEFAULT_OUT, cache: Path = lp.DEFAULT_CACHE, offline: bool = False,
          allow_bottom: bool = True) -> dict:
    plan = lp.build_plan(allow_bottom=allow_bottom)
    problems = lp.validate(plan)
    if problems:
        raise SystemExit("layout plan has problems:\n  " + "\n  ".join(problems))
    text, stats = build_board(plan, FootprintSource(cache, offline))
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    out.with_suffix(".kicad_pro").write_text(json.dumps(project(plan, out.stem), indent=2) + "\n")
    out.with_suffix(".kicad_dru").write_text(lp.dru_text(plan))
    stats.update(board=str(out), bytes=len(text), nets=len(bs.nets()), vias=len(plan.vias),
                 zones=len(plan.zones), silk=len(plan.silk))
    return stats


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Write the placed (unrouted) KiCad 9 project.")
    ap.add_argument("-o", "--output", type=Path, default=DEFAULT_OUT)
    ap.add_argument("--cache", type=Path, default=lp.DEFAULT_CACHE,
                    help="footprint cache ($KICAD_FP_CACHE, default ~/.cache/esp32p4-footprints)")
    ap.add_argument("--offline", action="store_true", help="never download footprints")
    ap.add_argument("--top-only", action="store_true", help="never place SoC-ring parts on B.Cu")
    args = ap.parse_args(argv)
    stats = write(args.output, args.cache, args.offline, not args.top_only)
    print(json.dumps(stats, indent=1))
    return 0


