class Q(str):
    """A quoted string atom (everything else is a bare symbol or number)."""


_TOKEN = re.compile(r'\s*(\(|\)|"(?:[^"\\]|\\.)*"|[^\s()"]+)')


def parse(text: str) -> list:
    stack: list[list] = [[]]
    for m in _TOKEN.finditer(text):
        tok = m.group(1)
        if tok == "(":
            stack.append([])
        elif tok == ")":
            node = stack.pop()
            stack[-1].append(node)
        elif tok.startswith('"'):
            stack[-1].append(Q(re.sub(r'\\(.)', r'\1', tok[1:-1])))
        else:
            stack[-1].append(tok)
    return stack[0][0]


def num(v: float) -> str:
    s = f"{v:.6f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def atom(a) -> str:
    if isinstance(a, Q):
        return '"' + a.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'
    if isinstance(a, float):
        return num(a)
    return str(a)


def dump(node, depth: int = 0) -> str:
    """KiCad-like layout: atoms on the head line, each child list on its own line."""
    if not isinstance(node, list):
        return atom(node)
    atoms, kids = [], []
    for c in node:
        (kids if isinstance(c, list) else atoms if not kids else kids).append(c)
    head = "(" + " ".join(atom(a) for a in atoms)
    if not kids:
        return head + ")"
    if node[0] == "pts":                      # polygons: several xy per line
        xy = [dump(k) for k in kids]
        lines = [" ".join(xy[i:i + 6]) for i in range(0, len(xy), 6)]
        pad = "\t" * (depth + 1)
        return head + "\n" + "\n".join(pad + ln for ln in lines) + "\n" + "\t" * depth + ")"
    pad = "\t" * (depth + 1)
    body = "\n".join(pad + dump(k, depth + 1) for k in kids)
    return head + "\n" + body + "\n" + "\t" * depth + ")"


def child(node: list, key: str) -> list | None:
    for c in node[1:]:
        if isinstance(c, list) and c and c[0] == key:
            return c
    return None


def children(node: list, key: str) -> list[list]:
    return [c for c in node[1:] if isinstance(c, list) and c and c[0] == key]


