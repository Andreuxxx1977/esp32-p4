def stackup() -> list:
    """Physical stack-up from impedance.STACKUP (1.6 mm, 1+2+1 HDI)."""
    s = ["stackup", ["layer", Q("F.SilkS"), ["type", Q("Top Silk Screen")]],
         ["layer", Q("F.Paste"), ["type", Q("Top Solder Paste")]],
         ["layer", Q("F.Mask"), ["type", Q("Top Solder Mask")]]]
    n = 0
    for layer in imp.STACKUP:
        if layer.kind == "copper":
            s.append(["layer", Q(layer.name), ["type", Q("copper")], ["thickness", layer.thickness_mm]])
        else:
            n += 1
            kind = "core" if "core" in layer.material.lower() else "prepreg"
            s.append(["layer", Q(f"dielectric {n}"), ["type", Q(kind)], ["thickness", layer.thickness_mm],
                      ["material", Q("FR4")], ["epsilon_r", layer.er], ["loss_tangent", 0.02]])
    s += [["layer", Q("B.Mask"), ["type", Q("Bottom Solder Mask")]],
          ["layer", Q("B.Paste"), ["type", Q("Bottom Solder Paste")]],
          ["layer", Q("B.SilkS"), ["type", Q("Bottom Silk Screen")]],
          ["copper_finish", Q("ENIG")], ["dielectric_constraints", "yes"]]
    return s


def stroke(width: float) -> list:
    return ["stroke", ["width", width], ["type", "default"]]


def board_graphics(plan: lp.Plan, uu: Uuids) -> list[list]:
    out = []
    for g in plan.graphics:
        pts = [board_xy(*p) for p in g.pts]
        if g.kind == "line":
            out.append(["gr_line", ["start", *pts[0]], ["end", *pts[1]], stroke(g.width),
                        ["layer", Q(g.layer)], ["uuid", uu("gr")]])
        elif g.kind == "arc":
            out.append(["gr_arc", ["start", *pts[0]], ["mid", *pts[1]], ["end", *pts[2]], stroke(g.width),
                        ["layer", Q(g.layer)], ["uuid", uu("gr")]])
        elif g.kind == "rect":
            out.append(["gr_rect", ["start", *pts[0]], ["end", *pts[1]], stroke(g.width),
                        ["fill", "yes" if g.filled else "no"], ["layer", Q(g.layer)], ["uuid", uu("gr")]])
        elif g.kind == "circle":
            out.append(["gr_circle", ["center", *pts[0]], ["end", *pts[1]], stroke(g.width),
                        ["fill", "no"], ["layer", Q(g.layer)], ["uuid", uu("gr")]])
        elif g.kind == "text":
            out.append(["gr_text", Q(g.text), ["at", *pts[0], 0.0], ["layer", Q(g.layer)],
                        ["uuid", uu("gr")], ["effects", ["font", ["size", 1.0, 1.0], ["thickness", 0.15]]]])
    for t in plan.silk:
        out.append(["gr_text", Q(t.text), ["at", *board_xy(t.x, t.y), t.angle], ["layer", Q(t.layer)],
                    ["uuid", uu("silk")],
                    ["effects", ["font", ["size", t.size, t.glyph_width], ["thickness", t.thickness]]]])   # (size H W)
    return out


def board_zones(plan: lp.Plan, nets: dict[str, int], uu: Uuids) -> list[list]:
    out = []
    for z in plan.zones:
        layers = ["layer", Q(z.layers[0])] if len(z.layers) == 1 else ["layers", *[Q(x) for x in z.layers]]
        pts = ["pts", *[["xy", *board_xy(x, y)] for x, y in z.polygon]]
        if z.rule_area:
            ko = lambda k: "not_allowed" if k in z.keepout else "allowed"  # noqa: E731
            out.append(["zone", ["net", 0], ["net_name", Q("")], layers, ["uuid", uu("zone")],
                        ["name", Q(z.name)], ["hatch", "edge", 0.5], ["connect_pads", ["clearance", 0]],
                        ["min_thickness", 0.25], ["filled_areas_thickness", "no"],
                        ["keepout", ["tracks", ko("tracks")], ["vias", ko("vias")], ["pads", ko("pads")],
                         ["copperpour", ko("pours")], ["footprints", ko("footprints")]],
                        ["placement", ["enabled", "no"], ["sheetname", Q("")]],
                        ["fill", ["thermal_gap", 0.5], ["thermal_bridge_width", 0.5]], ["polygon", pts]])
            continue
        zone = ["zone", ["net", nets[z.net]], ["net_name", Q(z.net)], layers, ["uuid", uu("zone")],
                ["name", Q(z.name)], ["hatch", "edge", 0.5]]
        if z.priority:
            zone.append(["priority", z.priority])
        connect = ["connect_pads", "yes"] if z.connection == "solid" else ["connect_pads"]
        zone += [connect + [["clearance", lp.ZONE_CLEARANCE_MM]], ["min_thickness", lp.ZONE_MIN_WIDTH_MM],
                 ["filled_areas_thickness", "no"],
                 ["fill", ["thermal_gap", 0.2], ["thermal_bridge_width", 0.25]], ["polygon", pts]]
        out.append(zone)
    return out


def build_board(plan: lp.Plan, src: FootprintSource) -> tuple[str, dict]:
    uu = Uuids()
    comps = {c.ref: c for c in bs.COMPONENTS}
    net_names = sorted(bs.nets())
    nets = {name: i for i, name in enumerate(net_names, 1)}
    ox, oy = board_xy(0.0, 0.0)
    r = lp.DESIGN_RULES
    n_b = sum(1 for p in plan.placements.values() if p.side == "B")
    board = [
        "kicad_pcb", ["version", FILE_VERSION], ["generator", Q("esp32p4_write_kicad_pcb")],
        ["generator_version", Q("9.0")],
        ["general", ["thickness", r["board_thickness"]], ["legacy_teardrops", "no"]],
        ["paper", Q("A4")],
        ["title_block", ["title", Q("ESP32-P4 Extreme Performance")], ["rev", Q("A")],
         ["company", Q("github.com/Andreuxxx1977/esp32-p4 -- CERN-OHL-P-2.0")],
         ["comment", 1, Q("PLACED BUT UNROUTED: ratsnest only, zones unfilled (press B), no tracks.")],
         ["comment", 2, Q("Generated by hardware/pcbnew/write_kicad_pcb.py from hardware/lib/board_spec.py.")],
         ["comment", 3, Q(f"Design origin = SoC centre = aux/grid origin; {n_b} parts on B.Cu.")],
         ["comment", 4, Q("Stack-up: 4L 1.6 mm HDI 1+2+1 (see hardware/lib/impedance.py).")]],
        ["layers", *[[i, Q(n), t] + ([Q(u)] if u else []) for i, n, t, u in LAYER_TABLE]],
        ["setup", stackup(), ["pad_to_mask_clearance", 0],
         ["allow_soldermask_bridges_in_footprints", "no"], ["tenting", "front", "back"],
         ["aux_axis_origin", ox, oy], ["grid_origin", ox, oy], ["pcbplotparams", *PLOT_PARAMS]],
        ["net", 0, Q("")], *[["net", i, Q(n)] for n, i in nets.items()],
    ]
    stats = {"footprints": 0, "pads_with_net": 0}
    for ref in sorted(plan.placements, key=lp.comp_sort_key):
        pl = plan.placements[ref]
        placer = Placer(pl, comps.get(ref), nets, uu)
        fp = placer.build(src.get(pl.lib_id))
        board.append(fp)
        stats["footprints"] += 1
        stats["pads_with_net"] += sum(1 for p in children(fp, "pad") if child(p, "net"))
    board += board_graphics(plan, uu)
    for v in plan.vias:
        board.append(["via", ["at", *board_xy(v.x, v.y)], ["size", v.diameter], ["drill", v.drill],
                      ["layers", Q("F.Cu"), Q("B.Cu")], ["net", nets[v.net]], ["uuid", uu("via")]])
    board += board_zones(plan, nets, uu)
    board.append(["embedded_fonts", "no"])
    return dump(board) + "\n", stats


