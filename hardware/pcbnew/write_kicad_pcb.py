OX, OY = lp.PAGE_ORIGIN_MM


def board_xy(x: float, y: float) -> tuple[float, float]:
    return round(x + OX, 6), round(y + OY, 6)


def norm360(a: float) -> float:
    a = round(a % 360.0, 6)
    return 0.0 if a in (0.0, 360.0) else a


def norm180(a: float) -> float:
    a = norm360(a)
    return a - 360.0 if a > 180.0 else a


def swap_layer(name: str) -> str:
    if name.startswith("F."):
        return "B." + name[2:]
    if name.startswith("B."):
        return "F." + name[2:]
    return name


class Uuids:
    def __init__(self) -> None:
        self.n = 0

    def __call__(self, scope: str) -> Q:
        self.n += 1
        return Q(str(uuid.uuid5(UUID_NS, f"{scope}/{self.n}")))


